def prepare_fn():
    """Fresh import of the repo's harness/churn_features.prepare (never a copy)."""
    sys.path.insert(0, str(REPO / "harness"))
    import churn_features  # type: ignore
    churn_features = importlib.reload(churn_features)
    return churn_features.prepare


def load(features=None, labels=None, n_max=None, seed=SEED):
    """Returns df (features+labels, one row per account), X_all (prepared features + raw: columns, account_id),
    reg (bool mask: regular, non-persona accounts), prep_note."""
    features = Path(features or os.environ.get("TM_BENCH_FEATURES", DEFAULT_FEATURES))
    labels = Path(labels or os.environ.get("TM_BENCH_LABELS", DEFAULT_LABELS))
    f = pd.read_csv(features)
    lab = pd.read_csv(labels)
    assert f["account_id"].is_unique and lab["account_id"].is_unique
    if "is_persona" not in f:
        f["is_persona"] = 0
    # leak guard: every labels.csv column except account_id / is_persona must never be a feature
    label_cols = [c for c in lab.columns if c not in ("account_id", "is_persona")]
    leaked = [c for c in f.columns if c in label_cols or re.search(LEAK_RE, c)]
    assert not leaked, f"leak columns in features: {leaked}"
    df = f.merge(lab.drop(columns=["is_persona"], errors="ignore"), on="account_id", how="inner", validate="1:1")
    assert len(df) == len(f), "features/labels account mismatch"
    if n_max and (df["is_persona"] == 0).sum() > n_max:  # stratified cap on regular accounts (personas kept)
        reg_ix = df.index[df["is_persona"] == 0]
        strat = df.loc[reg_ix, "churn_90d"] if "churn_90d" in df else None
        keep, _ = train_test_split(reg_ix, train_size=int(n_max), stratify=strat, random_state=seed)
        df = df.loc[sorted(set(keep) | set(df.index[df["is_persona"] == 1]))].reset_index(drop=True)
        f = f.set_index("account_id").loc[df["account_id"]].reset_index()
    prepare = prepare_fn()
    P = prepare(f.copy())
    if "account_id" in P.columns:
        P = P.set_index("account_id")
    P = P.loc[df["account_id"]]
    bad = [c for c in P.columns if c in label_cols or c == "is_persona" or re.search(LEAK_RE, c)]
    assert not bad, bad
    fr = f.set_index("account_id").loc[df["account_id"]]
    for c in RAW:
        if c in fr.columns and c not in P.columns:
            P["raw:" + c] = fr[c].astype(float).values
    X_all = P.reset_index().rename(columns={"index": "account_id"})
    reg = (df["is_persona"] == 0).values
    note = f"harness/churn_features.prepare() (imported at run time); features={features}; labels={labels}"
    return df, X_all, reg, note


def load_tstr(train_features, train_labels, test_features=None, test_labels=None):
    """Train-on-synthetic / test-on-real. The synthetic frame is cut to the real features.csv columns (enrichment
    columns such as income band / job change are dropped so inputs match Model A), both frames go through ONE
    prepare() call (same dummies, same fill medians), then split back. Returns (syn_df, syn_X, real_df, real_X,
    real_reg, leak_report)."""
    test_features = Path(test_features or os.environ.get("TM_BENCH_FEATURES", DEFAULT_FEATURES))
    test_labels = Path(test_labels or os.environ.get("TM_BENCH_LABELS", DEFAULT_LABELS))
    fs, ls = pd.read_csv(train_features), pd.read_csv(train_labels)
    fr, lr = pd.read_csv(test_features), pd.read_csv(test_labels)
    label_cols = set(lr.columns) | set(ls.columns)
    label_cols -= {"account_id", "is_persona"}
    report = {"synthetic_extra_columns_dropped": [c for c in fs.columns if c not in fr.columns],
              "synthetic_cols_matching_label_names": [c for c in fs.columns if c in label_cols],
              "synthetic_cols_matching_leak_regex": [c for c in fs.columns if re.search(LEAK_RE, c)],
              "id_overlap_real_vs_synthetic": int(len(set(fs.account_id) & set(fr.account_id)))}
    assert not report["synthetic_cols_matching_label_names"], report
    assert not report["synthetic_cols_matching_leak_regex"], report
    assert report["id_overlap_real_vs_synthetic"] == 0, report
    fs = fs[[c for c in fr.columns if c in fs.columns]]
    if "is_persona" not in fs:
        fs["is_persona"] = 0
    both = pd.concat([fs.assign(_src="syn"), fr.assign(_src="real")], ignore_index=True)
    src = both.pop("_src").values
    P = prepare_fn()(both.copy())
    if "account_id" in P.columns:
        P = P.set_index("account_id")
    P = P.loc[both["account_id"]]
    bad = [c for c in P.columns if c in label_cols or c == "is_persona" or re.search(LEAK_RE, c)]
    assert not bad, bad
    bi = both.set_index("account_id")
    for c in RAW:
        if c in bi.columns and c not in P.columns:
            P["raw:" + c] = bi[c].astype(float).values
    X = P.reset_index().rename(columns={"index": "account_id"})
    Xs, Xr = X[src == "syn"].reset_index(drop=True), X[src == "real"].reset_index(drop=True)
    ds = fs[["account_id"]].merge(ls.drop(columns=["is_persona"], errors="ignore"), on="account_id", validate="1:1")
    dr = fr.merge(lr.drop(columns=["is_persona"], errors="ignore"), on="account_id", validate="1:1")
    assert (ds.account_id.values == Xs.account_id.values).all() and (dr.account_id.values == Xr.account_id.values).all()
    report["n_features_after_prepare"] = int(sum(not str(c).startswith("raw:") for c in X.columns) - 1)
    return ds, Xs, dr, Xr, (dr["is_persona"] == 0).values, report


# ---------------- models (tm-harness ChurnModel shape) ----------------
def _logit(p):
    p = np.clip(p, 1e-6, 1 - 1e-6)
    return np.log(p / (1 - p))


def _fmt(name, val, contrib):
    v = f"{val:.3g}" if isinstance(val, (float, np.floating)) else str(val)
    return f"{name}={v} ({contrib:+.2f})"


class ChurnModel:
    """name; fit(X, y); predict_proba(X) -> 1D P(positive); explain(X, k=3) -> account_id, risk_reason_1..k,
    stay_reason_1..k. X may carry account_id; it is never a feature."""
    name = "base"
    raw_contacts = False

    def _X(self, X):
        drop = ["account_id"] + [c for c in X.columns if str(c).startswith("raw:")
                                 and not (self.raw_contacts and c[4:] in RAW_CONTACTS)]
        return X.drop(columns=drop, errors="ignore")

    def set_reference(self, X):  # tm-harness calls this after fit
        self._set_ref(X); self.reference_ = self.ref_
        return self

    def _set_ref(self, X):
        Xf = self._X(X)
        self.ref_ = {c: Xf[c].median() for c in Xf.columns}

    def contributions(self, X) -> pd.DataFrame:  # occlusion vs the median account, logit units
        Xf = self._X(X).reset_index(drop=True)
        base = _logit(self.predict_proba(Xf))
        out = {}
        for c in Xf.columns:
            Xr = Xf.copy(); Xr[c] = self.ref_[c]
            out[c] = base - _logit(self.predict_proba(Xr))
        return pd.DataFrame(out)

    def explain(self, X, k=3) -> pd.DataFrame:
        C = self.contributions(X)
        Xf = X.reset_index(drop=True)
        val = lambda i, c: Xf.at[i, c] if c in Xf else Xf.at[i, "raw:" + c]  # noqa: E731
        rows = []
        for i in range(len(C)):
            s = C.iloc[i].sort_values()
            r = {"account_id": Xf["account_id"].iloc[i] if "account_id" in Xf else i}
            pos, neg = s[s > 0][::-1][:k], s[s < 0][:k]
            for j in range(k):
                r[f"risk_reason_{j+1}"] = _fmt(pos.index[j], val(i, pos.index[j]), pos.iloc[j]) if j < len(pos) else ""
                r[f"stay_reason_{j+1}"] = _fmt(neg.index[j], val(i, neg.index[j]), neg.iloc[j]) if j < len(neg) else ""
            rows.append(r)
        return pd.DataFrame(rows)


class LogReg(ChurnModel):
    def __init__(self, class_weight=None, C=1.0, raw_contacts=False):
        self.class_weight, self.C, self.raw_contacts = class_weight, C, raw_contacts
        self.name = f"logreg_{'balanced' if class_weight else 'none'}" + ("_rawcontacts" if raw_contacts else "")

    def fit(self, X, y):
        Xf = self._X(X)
        self.cols_ = list(Xf.columns)
        self.pipe_ = Pipeline([("imp", SimpleImputer(strategy="median")), ("sc", StandardScaler()),
                               ("lr", LogisticRegression(C=self.C, class_weight=self.class_weight, max_iter=5000))])
        self.pipe_.fit(Xf, y)
        self.zmean_ = self.pipe_[:-1].transform(Xf).mean(axis=0)
        return self

    def predict_proba(self, X):
        return self.pipe_.predict_proba(self._X(X))[:, 1]

    def coefs(self):
        return pd.Series(self.pipe_.named_steps["lr"].coef_[0], index=self.cols_)

    def contributions(self, X):  # exact additive logit contributions vs the training-mean account
        Z = self.pipe_[:-1].transform(self._X(X))
        return pd.DataFrame((Z - self.zmean_) * self.pipe_.named_steps["lr"].coef_[0], columns=self.cols_)


class GBM(ChurnModel):
    def __init__(self, calibration=None, raw_contacts=False, default=False, seed=SEED):
        self.calibration, self.raw_contacts, self.default = calibration, raw_contacts, default
        self.kw = (dict(random_state=seed) if default else
                   dict(max_depth=3, max_iter=200, learning_rate=0.05, early_stopping=True, validation_fraction=0.15,
                        n_iter_no_change=20, l2_regularization=1.0, min_samples_leaf=40, random_state=seed))
        self.name = ("hgb_default" if default else "hgb") + (f"_{calibration}" if calibration else "") + \
            ("_rawcontacts" if raw_contacts else "")

    def fit(self, X, y):
        Xf = self._X(X)
        base = HistGradientBoostingClassifier(**self.kw)
        self.est_ = CalibratedClassifierCV(base, method=self.calibration, cv=3) if self.calibration else base
        self.est_.fit(Xf, y)
        self._set_ref(Xf)
        return self

    def predict_proba(self, X):
        return self.est_.predict_proba(self._X(X))[:, 1]


class SkGBDefault(ChurnModel):
    """Untuned sklearn GradientBoostingClassifier() with all defaults."""
    name = "gbc_default"

    def __init__(self, seed=SEED):
        self.seed = seed

    def fit(self, X, y):
        from sklearn.ensemble import GradientBoostingClassifier
        Xf = self._X(X)
        self.est_ = GradientBoostingClassifier(random_state=self.seed).fit(Xf, y)
        self._set_ref(Xf)
        return self

    def predict_proba(self, X):
        return self.est_.predict_proba(self._X(X))[:, 1]


class RuleModel(ChurnModel):
    """Reference rule: a hand-made score; P = isotonic (monotone) map of score -> train positive rate."""
    def __init__(self, name, score_fn, feature):
        self.name, self.score_fn, self.feature = name, score_fn, feature

    def fit(self, X, y):
        from sklearn.isotonic import IsotonicRegression
        s = self.score_fn(X)
        self.iso_ = IsotonicRegression(out_of_bounds="clip", y_min=1e-4, y_max=1 - 1e-4, increasing=True).fit(s, y)
        self.ref_p_ = float(self.iso_.predict([np.median(s)])[0])
        return self

    def score(self, X):
        return self.score_fn(X)

    def predict_proba(self, X):
        return self.iso_.predict(self.score_fn(X))

    def contributions(self, X):
        p = self.predict_proba(X)
        return pd.DataFrame({self.feature: _logit(p) - _logit(np.full_like(p, self.ref_p_))})


def _col(X, c):
    return (X[c] if c in X else X["raw:" + c]).astype(float).values


def support_count_score(X):
    """Ranking by raw support_90d contact count (continuous)."""
    return _col(X, "support_90d")


def support_3plus_score(X):
    """Binary '3+ support contacts in 90d' rule (tm-harness backtest rule): 1 if support_90d >= 3 else 0."""
    return (np.nan_to_num(_col(X, "support_90d")) >= 3).astype(float)


def near_cap_score(X):
    """n_lines_over_cap_3m, tie-broken by account data / (per-line cap x lines); unlimited plans score 0."""
    cap = _col(X, "plan_data_cap_gb")
    ratio = np.where(np.isnan(cap) | (cap <= 0), 0.0,
                     _col(X, "data_gb_3m_avg") / (np.nan_to_num(cap, nan=1.0) * np.maximum(_col(X, "n_lines"), 1)))
    return _col(X, "n_lines_over_cap_3m") + np.clip(ratio, 0, 0.999)


def near_cap_binary_score(X):
    """tm-harness upgrade rule: n_lines_over_cap > 0 or 3-mo avg usage >= 90% of the cap; never unlimited."""
    cap = _col(X, "plan_data_cap_gb")
    limited = ~(np.isnan(cap) | (cap <= 0))
    per_line = _col(X, "data_gb_3m_avg") / np.maximum(_col(X, "n_lines"), 1)
    near = limited & (per_line >= 0.9 * np.nan_to_num(cap, nan=np.inf))
    return (limited & ((_col(X, "n_lines_over_cap_3m") > 0) | near)).astype(float)


def candidates(label="churn_90d"):
    rule = (RuleModel("rule_near_cap", near_cap_score, "n_lines_over_cap_3m") if label == "upgrade_90d"
            else RuleModel("rule_support_90d_count", support_count_score, "support_90d"))
    return [rule, LogReg(None), LogReg("balanced"), GBM(None), GBM("isotonic"), GBM("sigmoid"),
            LogReg(None, raw_contacts=True), GBM(None, raw_contacts=True)]


def clone(m):
    c = type(m).__new__(type(m)); c.__dict__ = {k: v for k, v in m.__dict__.items() if not k.endswith("_")}
    return c


