def md_table(res):
    h = "| model | " + " | ".join(COLS) + " |\n|" + "---|" * (len(COLS) + 1) + "\n"
    for n, r in res.items():
        h += f"| {n} | " + " | ".join("" if r.get(c) is None else f"{r[c]:.4f}" if not c.endswith(
            ("_median",)) else f"{r[c]:.3f}" for c in COLS) + " |\n"
    return h


def cli(desc):
    ap = argparse.ArgumentParser(description=desc + " ALL NUMBERS SYNTHETIC.")
    ap.add_argument("--features", default=None, help="features.csv (default harness/out/features.csv or "
                    "$TM_BENCH_FEATURES)")
    ap.add_argument("--labels", default=None, help="labels.csv (default harness/out/labels.csv or $TM_BENCH_LABELS)")
    ap.add_argument("--n-max", type=int, default=None, help="cap regular accounts (stratified subsample)")
    ap.add_argument("--targets", nargs="+", default=TARGETS)
    return ap


def main():
    a = cli("5-fold CV bench of cheap candidates.").parse_args()
    df, X_all, reg, note = load(a.features, a.labels, a.n_max)
    OUT.mkdir(parents=True, exist_ok=True)
    out = {"SYNTHETIC": True, "framing": "pipeline check on synthetic labels generated from these features; NOT "
           "real-world accuracy", "prep": note, "n_regular": int(reg.sum()), "n_persona": int((~reg).sum()),
           "features": [c for c in X_all.columns if c != "account_id"], "labels": {}}
    md = ["# 5-fold CV bench (SYNTHETIC data, SYNTHETIC labels)\n", f"- {note}",
          f"- regular accounts: {int(reg.sum())}; personas held out: {int((~reg).sum())}",
          f"- model features from prepare(): {sum(not str(c).startswith('raw:') for c in X_all.columns) - 1}\n"]
    pers = []
    for lab in a.targets:
        if lab not in df:
            print("skip (missing):", lab); continue
        res, _ = run_label(lab, df, X_all, reg)
        pc, ps = persona_check(df, X_all, reg, lab)
        pers.append(ps)
        out["labels"][lab] = {"positives": int(df.loc[reg, lab].sum()), "prevalence": float(df.loc[reg, lab].mean()),
                              "cv": res, "persona_check_PROVISIONAL": pc}
        md += [f"## {lab} (positives {int(df.loc[reg, lab].sum())}/{int(reg.sum())}, synthetic)\n", md_table(res)]
        if pc:
            md.append("Persona check (PROVISIONAL; high = >=90th pct, low = <50th): " +
                      ", ".join(f"{m} {v['n_pass']}/{len(v) - 1}" for m, v in pc.items()) + "\n")
    (OUT / "cv_results.json").write_text(json.dumps(out, indent=1, default=float))
    (OUT / "cv_results.md").write_text("\n".join(md))
    if pers:
        pd.concat(pers).to_csv(OUT / "persona_scores.csv", index=False)
    print("\n".join(md))


if __name__ == "__main__":
    main()
